-- ---------------------------------
-- Helper function to emulate MySQL's ON UPDATE CURRENT_TIMESTAMP
-- ---------------------------------
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS '
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
' LANGUAGE plpgsql;

-- ---------------------------------
-- `users_demo`
-- Stores the main user account info.
-- ---------------------------------
CREATE TABLE IF NOT EXISTS users_demo (
id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
first_name VARCHAR(50),
last_name VARCHAR(50),
email VARCHAR(255) NOT NULL,
public_email BOOLEAN DEFAULT FALSE,
phone VARCHAR(255),
public_phone BOOLEAN DEFAULT FALSE,
password_hash VARCHAR(255),
created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
deleted_at TIMESTAMPTZ,

CONSTRAINT uq_users_email UNIQUE (email)
);

CREATE INDEX IF NOT EXISTS idx_users_name ON users_demo (last_name, first_name);

DROP TRIGGER IF EXISTS trg_users_updated_at ON users_demo;
CREATE TRIGGER trg_users_updated_at
BEFORE UPDATE ON users_demo
FOR EACH ROW
EXECUTE FUNCTION update_updated_at_column();

-- ---------------------------------
-- `roles_demo`
-- Stores the available roles (e.g., ADMIN, USER, GUEST).
-- ---------------------------------
CREATE TABLE IF NOT EXISTS roles_demo (
id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
name VARCHAR(50) NOT NULL UNIQUE,
description VARCHAR(255)
);

-- ---------------------------------
-- `permissions_demo`
-- Stores specific actions (e.g., CREATE_POST, DELETE_USER).
-- ---------------------------------
CREATE TABLE IF NOT EXISTS permissions_demo (
id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
name VARCHAR(100) NOT NULL UNIQUE,
description VARCHAR(255)
);

-- ---------------------------------
-- `user_roles_demo` (Junction Table)
-- Maps users to roles (Many-to-Many).
-- ---------------------------------
CREATE TABLE IF NOT EXISTS user_roles_demo (
user_id INT NOT NULL,
role_id INT NOT NULL,
PRIMARY KEY (user_id, role_id),
FOREIGN KEY (user_id) REFERENCES users_demo(id) ON DELETE CASCADE,
FOREIGN KEY (role_id) REFERENCES roles_demo(id) ON DELETE CASCADE
);

-- ---------------------------------
-- `permission_role_demo` (Junction Table)
-- Maps permissions to roles (Many-to-Many).
-- ---------------------------------
CREATE TABLE IF NOT EXISTS permission_role_demo (
permission_id INT NOT NULL,
role_id INT NOT NULL,
PRIMARY KEY (permission_id, role_id),
FOREIGN KEY (permission_id) REFERENCES permissions_demo(id) ON DELETE CASCADE,
FOREIGN KEY (role_id) REFERENCES roles_demo(id) ON DELETE CASCADE
);


CREATE TABLE IF NOT EXISTS league (
      league_id SERIAL PRIMARY KEY,
      name VARCHAR(50) NOT NULL UNIQUE,
abbreviation VARCHAR(10) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS brand (
     brand_id SERIAL PRIMARY KEY,
     name VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS athlete (
       athlete_id SERIAL PRIMARY KEY,
       league_id INT NOT NULL REFERENCES league(league_id) ON DELETE RESTRICT,
full_name VARCHAR(120) NOT NULL,
active BOOLEAN DEFAULT TRUE,
CONSTRAINT uq_athlete UNIQUE (league_id, full_name)
);

CREATE TABLE IF NOT EXISTS tag (
   tag_id SERIAL PRIMARY KEY,
   label VARCHAR(50) NOT NULL UNIQUE,
status_type VARCHAR(20) DEFAULT 'Standard'
);

CREATE TABLE IF NOT EXISTS shoe (
    shoe_id SERIAL PRIMARY KEY,
    brand_id INT NOT NULL REFERENCES brand(brand_id) ON DELETE RESTRICT,
athlete_id INT NOT NULL REFERENCES athlete(athlete_id) ON DELETE CASCADE,
name VARCHAR(150) NOT NULL,
featured_image_url TEXT,
intro_year INT,
status_badge VARCHAR(30) DEFAULT 'Standard',
description TEXT,
espn_anchor VARCHAR(100),
created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS shoe_tag (
        shoe_id INT NOT NULL REFERENCES shoe(shoe_id) ON DELETE CASCADE,
tag_id INT NOT NULL REFERENCES tag(tag_id) ON DELETE CASCADE,
PRIMARY KEY (shoe_id, tag_id)
);

CREATE TABLE IF NOT EXISTS shoe_model (
          model_id SERIAL PRIMARY KEY,
          shoe_id INT NOT NULL REFERENCES shoe(shoe_id) ON DELETE CASCADE,
model_name VARCHAR(150) NOT NULL,
release_year INT,
image_url TEXT
);

CREATE TABLE IF NOT EXISTS shoe_image (
          image_id SERIAL PRIMARY KEY,
          shoe_id INT NOT NULL REFERENCES shoe(shoe_id) ON DELETE CASCADE,
model_id INT REFERENCES shoe_model(model_id) ON DELETE SET NULL,
image_url TEXT NOT NULL,
image_type VARCHAR(30) DEFAULT 'gallery'
);